// Embeds python/gigaam_server.py into src/generated/gigaam-server-py.ts.
// The host bundle must be self-contained: the plugin directory is not
// available on remote machines, so the Python source ships as a string.
// Run `npm run embed` after editing the Python file; `npm test` checks it.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export function renderEmbeddedPython(source) {
  const sha = createHash("sha256").update(source).digest("hex");
  return [
    "// Generated by scripts/embed-python.mjs from python/gigaam_server.py. Do not edit.",
    `export const GIGAAM_SERVER_PY_SHA256 = ${JSON.stringify(sha)};`,
    `export const GIGAAM_SERVER_PY = ${JSON.stringify(source)};`,
    "",
  ].join("\n");
}

export const sourcePath = join(root, "python", "gigaam_server.py");
export const generatedPath = join(root, "src", "generated", "gigaam-server-py.ts");

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(dirname(generatedPath), { recursive: true });
  writeFileSync(generatedPath, renderEmbeddedPython(readFileSync(sourcePath, "utf8")));
  console.log(`wrote ${generatedPath}`);
}
